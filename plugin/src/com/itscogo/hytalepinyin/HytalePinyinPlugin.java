package com.itscogo.hytalepinyin;

import com.hypixel.hytale.component.Ref;
import com.hypixel.hytale.protocol.UpdateType;
import com.hypixel.hytale.protocol.packets.assets.UpdateTranslations;
import com.hypixel.hytale.server.core.asset.LoadAssetEvent;
import com.hypixel.hytale.server.core.asset.type.item.config.Item;
import com.hypixel.hytale.server.core.Message;
import com.hypixel.hytale.server.core.event.events.player.PlayerReadyEvent;
import com.hypixel.hytale.server.core.modules.i18n.I18nModule;
import com.hypixel.hytale.server.core.modules.i18n.parser.LangFileParser;
import com.hypixel.hytale.server.core.plugin.JavaPlugin;
import com.hypixel.hytale.server.core.plugin.JavaPluginInit;
import com.hypixel.hytale.server.core.universe.PlayerRef;
import com.hypixel.hytale.server.core.universe.world.storage.EntityStore;

import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collections;
import java.util.HashMap;
import java.util.Map;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicLong;
import java.util.logging.Level;

/**
 * HytalePinyin: Hytale in Chinese with pinyin, for learners.
 *
 * Why a plugin and not just a .lang file: Hytale keeps the FIRST definition of
 * each translation key, and the game's own pack always loads first, so a mod's
 * .lang file can add new keys but never replace existing ones. This plugin
 * replaces them in memory instead:
 *
 *  1. After all asset packs are loaded, it writes our translations into the
 *     server's translation table (I18nModule), so every player who joins
 *     already receives them.
 *  2. /hanzi colors and /hanzi english send one player an "update
 *     translations" packet with the variant of the texts they chose, so each
 *     player can switch tone colours and the English lines live, without
 *     affecting anyone else. Settings are saved and re-sent when they join.
 */
public class HytalePinyinPlugin extends JavaPlugin {

    /** The language our texts are for: only players with the game in zh-CN get them. */
    static final String LANGUAGE = "zh-CN";

    /**
     * Our texts in the four combinations of the two settings, generated by
     * glossary/build.py: key -> text. Index with variant(tones, english).
     */
    private final Map<String, Map<String, String>> variants = new ConcurrentHashMap<>();
    /** Every key any variant has, to remove the ones a variant leaves out. */
    private final Set<String> allKeys = ConcurrentHashMap.newKeySet();
    /** Each player's settings; players not in here use the defaults. */
    private final Map<UUID, Settings> settings = new ConcurrentHashMap<>();
    /** Players who already got the "check your client patch" note (see warnAboutClientPatch). */
    private final Set<UUID> notified = ConcurrentHashMap.newKeySet();
    /** The fonts and menus of the Hytale client on this computer, if there is one (see ClientPatch). */
    private ClientPatch clientPatch;
    /** What installing them did when the server started. */
    private volatile ClientPatch.Result clientPatchResult = new ClientPatch.Result(ClientPatch.State.NO_CLIENT, java.util.List.of());

    /** "pīnyīn" in the small letters the client patch adds (see tools/small_pinyin.py). */
    private static final String SMALL_PINYIN = "\uE10F\uE122\uE10D\uE118\uE122\uE10D";
    private static final String ORANGE = "#f0a347";

    /**
     * A player's display settings. A Java "record" is a small immutable class
     * whose fields, constructor, equals() and toString() are generated for us.
     */
    record Settings(boolean tones, boolean english) {
        static final Settings DEFAULT = new Settings(false, false);
    }

    // In Java the constructor must call the parent's: Hytale passes in the
    // plugin's manifest, folder and class loader through JavaPluginInit.
    public HytalePinyinPlugin(JavaPluginInit init) {
        super(init);
    }

    @Override
    protected void setup() {
        for (boolean tones : new boolean[] {false, true}) {
            for (boolean english : new boolean[] {false, true}) {
                String name = variant(tones, english);
                Map<String, String> texts = readLangResource("/hytalepinyin/" + name + ".lang");
                variants.put(name, texts);
                allKeys.addAll(texts.keySet());
            }
        }
        loadSettings();
        installClientPatch();

        // LoadAssetEvent fires when the server (re)loads every asset pack.
        // I18nModule reads the .lang files at priority -32 (PRIORITY_LOAD_COMMON);
        // PRIORITY_LOAD_LATE (64) runs after it, so our values land on top.
        // The server table gets the default variant: what everyone sees first.
        getEventRegistry().register(LoadAssetEvent.PRIORITY_LOAD_LATE, LoadAssetEvent.class,
                event -> {
                    dumpGameTexts();
                    injectIntoServerTable(LANGUAGE, variants.get(variant(false, false)));
                    dumpItemKeys();
                });

        // A player who changed their settings gets their variant on joining.
        // PlayerReadyEvent is keyed by world, so registerGlobal hears every world.
        getEventRegistry().registerGlobal(PlayerReadyEvent.class, event -> {
            // Players are ECS entities: the event gives a reference to the
            // entity, and PlayerRef is one of its components.
            Ref<EntityStore> ref = event.getPlayerRef();
            PlayerRef player = ref.getStore().getComponent(ref, PlayerRef.getComponentType());
            if (player == null) {
                return;
            }
            Settings mine = settingsOf(player);
            if (!mine.equals(Settings.DEFAULT)) {
                sendTexts(player, mine);
            }
            warnAboutClientPatch(player);
        });

        getCommandRegistry().registerCommand(new HanziCommand(this));
    }

    /** Resource name of a variant: zh-CN, zh-CN.english, zh-CN.tones, zh-CN.tones.english. */
    static String variant(boolean tones, boolean english) {
        return LANGUAGE + (tones ? ".tones" : "") + (english ? ".english" : "");
    }

    Settings settingsOf(PlayerRef player) {
        return settings.getOrDefault(player.getUuid(), Settings.DEFAULT);
    }

    /** Saves a player's new settings and sends them the matching texts. */
    void change(PlayerRef player, Settings updated) {
        settings.put(player.getUuid(), updated);
        saveSettings();
        sendTexts(player, updated);
    }

    /**
     * Sends one player the texts of their settings, live. Only for players
     * playing in Chinese: anyone else would get Chinese item names.
     */
    private void sendTexts(PlayerRef player, Settings mine) {
        if (!LANGUAGE.equals(player.getLanguage())) {
            return;
        }
        Map<String, String> texts = variants.get(variant(mine.tones(), mine.english()));
        player.getPacketHandler().writeNoCache(new UpdateTranslations(UpdateType.AddOrUpdate, texts));
        // Keys this variant doesn't have (an English-only description) must go,
        // or the previous variant's text would stay on screen.
        Map<String, String> missing = new HashMap<>();
        for (String key : allKeys) {
            if (!texts.containsKey(key)) {
                missing.put(key, "");
            }
        }
        if (!missing.isEmpty()) {
            player.getPacketHandler().writeNoCache(new UpdateTranslations(UpdateType.Remove, missing));
        }
    }

    /**
     * In singleplayer, installs the fonts and menus with pinyin into the
     * Hytale client on this computer (see ClientPatch). Never stops the
     * server: if anything goes wrong it is logged and the game goes on.
     */
    private void installClientPatch() {
        try {
            Path serverJar = Path.of(I18nModule.class.getProtectionDomain().getCodeSource().getLocation().toURI());
            clientPatch = new ClientPatch(serverJar);
            clientPatchResult = clientPatch.install();
        } catch (Exception e) {
            clientPatchResult = new ClientPatch.Result(ClientPatch.State.INCOMPLETE, java.util.List.of(e.toString()));
        }
        logClientPatch("Client patch on this computer", clientPatchResult);
    }

    void logClientPatch(String what, ClientPatch.Result result) {
        getLogger().at(Level.INFO).log("%s: %s", what, result.state());
        for (String problem : result.problems()) {
            getLogger().at(Level.WARNING).log("Client patch: %s", problem);
        }
    }

    ClientPatch clientPatch() {
        return clientPatch;
    }

    /**
     * Tells players playing in Chinese what to do about the client patch.
     *
     * In singleplayer the plugin has just installed it, but the client only
     * reads its fonts and menus when it starts: until Hytale is restarted
     * some pinyin shows as boxes. On a dedicated server we can't see the
     * player's computer, so each player gets one line written in the small
     * letters: if it shows boxes, their client doesn't have the patch.
     */
    private void warnAboutClientPatch(PlayerRef player) {
        if (!LANGUAGE.equals(player.getLanguage())) {
            return;
        }
        switch (clientPatchResult.state()) {
            case CHANGED -> player.sendMessage(Message.raw("HytalePinyin: installed the fonts and menus with pinyin "
                    + "into Hytale. Restart Hytale once to see all the pinyin (until then some show as boxes).")
                    .color(ORANGE));
            case INCOMPLETE -> player.sendMessage(Message.raw("HytalePinyin: could not install every font and menu "
                    + "with pinyin into Hytale (see the log), so some pinyin may show as boxes. Is this mod "
                    + "version made for your Hytale version?").color(ORANGE));
            case NO_CLIENT -> {
                if (notified.add(player.getUuid())) {
                    player.sendMessage(Message.raw("HytalePinyin: if this word shows as boxes, (" + SMALL_PINYIN
                            + "), install HytalePinyin on your own computer too, open any singleplayer world "
                            + "with it once and restart Hytale.").color(ORANGE));
                    saveNotified();
                }
            }
            default -> {
                // INSTALLED, or DISABLED by the player with /hanzi restore
            }
        }
    }

    /** notified.txt in the plugin's data folder: one uuid per line. */
    private Path notifiedFile() {
        return getDataDirectory().resolve("notified.txt");
    }

    private synchronized void saveNotified() {
        try {
            Files.createDirectories(notifiedFile().getParent());
            Files.write(notifiedFile(), notified.stream().map(UUID::toString).toList(), StandardCharsets.UTF_8);
        } catch (Exception e) {
            getLogger().at(Level.WARNING).log("Could not save notified.txt: %s", e);
        }
    }

    /** settings.tsv in the plugin's data folder: uuid, tones, english. */
    private Path settingsFile() {
        return getDataDirectory().resolve("settings.tsv");
    }

    private void loadSettings() {
        try {
            if (Files.exists(notifiedFile())) {
                for (String line : Files.readAllLines(notifiedFile(), StandardCharsets.UTF_8)) {
                    if (!line.isBlank()) {
                        notified.add(UUID.fromString(line.strip()));
                    }
                }
            }
            if (!Files.exists(settingsFile())) {
                return;
            }
            for (String line : Files.readAllLines(settingsFile(), StandardCharsets.UTF_8)) {
                String[] cols = line.split("\t");
                if (cols.length == 3 && !cols[0].equals("uuid")) {
                    settings.put(UUID.fromString(cols[0]),
                            new Settings(Boolean.parseBoolean(cols[1]), Boolean.parseBoolean(cols[2])));
                }
            }
        } catch (Exception e) {
            getLogger().at(Level.WARNING).log("Could not read settings.tsv: %s", e);
        }
    }

    private synchronized void saveSettings() {
        StringBuilder tsv = new StringBuilder("uuid\ttones\tenglish\n");
        settings.forEach((uuid, s) -> tsv.append(uuid).append('\t').append(s.tones())
                .append('\t').append(s.english()).append('\n'));
        try {
            Files.createDirectories(settingsFile().getParent());
            Files.writeString(settingsFile(), tsv.toString(), StandardCharsets.UTF_8);
        } catch (Exception e) {
            getLogger().at(Level.WARNING).log("Could not save settings.tsv: %s", e);
        }
    }

    /**
     * Writes item-keys.tsv: which translation keys each item really uses.
     *
     * An item's name and description keys are usually server.items.<ID>.name
     * and .description, but an item can point at other keys, and children
     * inherit them from their parent (the mithril hatchet shows the crude
     * hatchet's description). The glossary script reads this file so it
     * never puts one item's name inside a description another item shares.
     */
    private void dumpItemKeys() {
        writeDataFile("item-keys.tsv", itemKeysTsv());
    }

    private String itemKeysTsv() {
        StringBuilder tsv = new StringBuilder("id\tname\tdescription\n");
        for (Map.Entry<String, Item> entry : Item.getAssetMap().getAssetMap().entrySet()) {
            Item item = entry.getValue();
            tsv.append(entry.getKey()).append('\t').append(item.getTranslationKey())
               .append('\t').append(item.getDescriptionTranslationKey()).append('\n');
        }
        return tsv.toString();
    }

    /**
     * Writes the game's own server texts (game-texts/<locale>/server.lang, in
     * .lang format) before ours replace them. The glossary script builds the
     * mod's texts from these, so after a game update there is no need to dig
     * them out of the 4 GB Assets.zip. Runs before injectIntoServerTable, so
     * the zh-CN file has the official texts, not ours.
     */
    @SuppressWarnings("unchecked")
    private void dumpGameTexts() {
        try {
            Field languagesField = I18nModule.class.getDeclaredField("languages");
            languagesField.setAccessible(true);
            Map<String, Map<String, String>> languages =
                    (Map<String, Map<String, String>>) languagesField.get(I18nModule.get());
            for (String locale : new String[] {"en-US", LANGUAGE}) {
                Map<String, String> texts = languages.getOrDefault(locale, Map.of());
                StringBuilder lang = new StringBuilder();
                texts.entrySet().stream()
                        .filter(e -> e.getKey().startsWith("server."))
                        .sorted(Map.Entry.comparingByKey())
                        .forEach(e -> lang.append(e.getKey().substring("server.".length())).append(" = ")
                                // back to the file's escapes, which the parser turned into real characters
                                .append(e.getValue().replace("\n", "\\n").replace("\t", "\\t")).append('\n'));
                writeDataFile("game-texts/" + locale + "/server.lang", lang.toString());
            }
        } catch (ReflectiveOperationException | RuntimeException e) {
            getLogger().at(Level.WARNING).log("Could not write the game texts: %s", e);
        }
    }

    private void writeDataFile(String name, String content) {
        try {
            Path file = getDataDirectory().resolve(name);
            Files.createDirectories(file.getParent());
            Files.writeString(file, content, StandardCharsets.UTF_8);
            getLogger().at(Level.INFO).log("Wrote %s", file.toAbsolutePath());
        } catch (Exception e) {
            getLogger().at(Level.WARNING).log("Could not write %s: %s", name, e);
        }
    }

    /**
     * Writes our texts into I18nModule's private table of translations.
     *
     * The server has no public method for replacing a translation, so this
     * uses reflection: it looks up the private fields by name and makes them
     * accessible. If a game update renames them, it logs a warning and the
     * game simply keeps its own texts (nothing crashes).
     */
    @SuppressWarnings("unchecked")
    private void injectIntoServerTable(String language, Map<String, String> texts) {
        try {
            I18nModule i18n = I18nModule.get();
            Field languagesField = I18nModule.class.getDeclaredField("languages");
            Field versionField = I18nModule.class.getDeclaredField("messagesVersion");
            languagesField.setAccessible(true);
            versionField.setAccessible(true);

            Map<String, Map<String, String>> languages = (Map<String, Map<String, String>>) languagesField.get(i18n);
            languages.computeIfAbsent(language, k -> new ConcurrentHashMap<>()).putAll(texts);
            // The module caches each language's table by version number;
            // bumping it makes the next player who joins get the new table.
            ((AtomicLong) versionField.get(i18n)).incrementAndGet();

            getLogger().at(Level.INFO).log("Replaced %d translations for %s", texts.size(), language);
        } catch (ReflectiveOperationException | RuntimeException e) {
            getLogger().at(Level.WARNING).log("Could not replace translations (%s); the game's own texts stay", e);
        }
    }

    /** Reads a .lang file bundled in the plugin JAR with the game's own parser. */
    private Map<String, String> readLangResource(String path) {
        try (InputStream in = HytalePinyinPlugin.class.getResourceAsStream(path)) {
            if (in == null) {
                getLogger().at(Level.WARNING).log("Missing resource %s", path);
                return Collections.emptyMap();
            }
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            return LangFileParser.parse(path, reader);
        } catch (Exception e) {
            getLogger().at(Level.WARNING).log("Could not read %s: %s", path, e);
            return Collections.emptyMap();
        }
    }
}
